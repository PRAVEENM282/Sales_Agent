"""
FastAPI application for Natural Language to SQL Sales Agent.
Exposes POST /query endpoint and integrates with MCP Server and SQLAgent.
"""

from typing import Any, Dict, List, Union
from fastapi import FastAPI, HTTPException, status
from pydantic import BaseModel, Field

from mcp_server import MCPServer, SecurityViolationError
from agent import SQLAgent, UnanswerableQuestionError

app = FastAPI(
    title="Sales Natural Language to SQL Agent",
    description="Translates natural language questions into safe SQL queries using MCP and LangChain.",
    version="1.0.0"
)

# Instantiate MCP Server and SQL Agent
mcp_server = MCPServer()
agent = SQLAgent(mcp_server=mcp_server)


class QueryRequest(BaseModel):
    question: str = Field(..., description="Natural language question about sales data")


class ChartData(BaseModel):
    labels: List[str] = Field(..., description="Labels for chart axes or series")
    values: List[Union[int, float]] = Field(..., description="Numeric values for chart bars or points")


class QueryResponse(BaseModel):
    sql: str = Field(..., description="The SQL query generated by the agent")
    results: List[Dict[str, Any]] = Field(..., description="Array of row objects from the query result")
    chart_data: ChartData = Field(..., description="Formatted labels and numeric values for chart visualization")


@app.get("/health")
def health_check():
    """Health check endpoint."""
    return {"status": "healthy"}


@app.post("/query", response_model=QueryResponse, status_code=status.HTTP_200_OK)
def query_sales(request: QueryRequest):
    """
    Translates a natural language question into a safe SQL query,
    executes it against SQLite via MCP Server, and returns structured results.
    """
    question = request.question.strip()
    if not question:
        raise HTTPException(
            status_code=status.HTTP_400_BAD_REQUEST,
            detail="Question cannot be empty."
        )

    try:
        sql, results, chart_data = agent.process_query(question)
        return QueryResponse(
            sql=sql,
            results=results,
            chart_data=ChartData(**chart_data)
        )
    except UnanswerableQuestionError as e:
        raise HTTPException(
            status_code=status.HTTP_400_BAD_REQUEST,
            detail=str(e)
        )
    except SecurityViolationError as e:
        raise HTTPException(
            status_code=status.HTTP_500_INTERNAL_SERVER_ERROR,
            detail=f"Security violation: {str(e)}"
        )
    except Exception as e:
        raise HTTPException(
            status_code=status.HTTP_500_INTERNAL_SERVER_ERROR,
            detail=f"Query execution error: {str(e)}"
        )


if __name__ == "__main__":
    import uvicorn
    uvicorn.run("main:app", host="0.0.0.0", port=8000, reload=True)
